using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace LabClean.Core;

/// <summary>Writes a <see cref="CleanResult"/> as JSON files and a human-readable Markdown report.</summary>
public static class Report
{
    public static readonly JsonSerializerOptions Json = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        WriteIndented = true,
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping, // keep µ, ×, ³ readable
        NumberHandling = JsonNumberHandling.AllowNamedFloatingPointLiterals,
    };

    private static readonly Dictionary<string, string> Icon = new() { ["error"] = "🔴", ["warning"] = "🟡", ["info"] = "🔵" };

    private static string F(double? v) => v is double d ? d.ToString("0.###", System.Globalization.CultureInfo.InvariantCulture) : "(blank)";

    /// <summary>Writes ASSESSMENT.md, assessment.json and (unless assessOnly) records.json and baselines.json.</summary>
    public static void WriteAll(CleanResult r, string sourceName, string dir, bool assessOnly = false)
    {
        Directory.CreateDirectory(dir);
        var assessment = new { source = sourceName, r.Summary, r.Issues, r.Changes, r.Schema, r.IdColumn };
        File.WriteAllText(Path.Combine(dir, "assessment.json"), JsonSerializer.Serialize(assessment, Json) + "\n");
        File.WriteAllText(Path.Combine(dir, "ASSESSMENT.md"), Markdown(r, sourceName));
        if (assessOnly) return;
        File.WriteAllText(Path.Combine(dir, "records.json"), JsonSerializer.Serialize(new { source = sourceName, r.Records }, Json) + "\n");
        File.WriteAllText(Path.Combine(dir, "baselines.json"), JsonSerializer.Serialize(new { source = sourceName, r.Baselines.Method, r.Baselines.Baselines }, Json) + "\n");
    }

    public static string Markdown(CleanResult r, string name)
    {
        var s = r.Summary;
        var sb = new StringBuilder();
        void L(string line = "") => sb.Append(line).Append('\n');

        L($"# Data assessment: {name}");
        L();
        L("Generated by `dotnet run --project tools/LabClean/src/LabClean.Cli`. Do not edit by hand.");
        L();
        L("## Summary");
        L();
        L("| | |");
        L("|---|---|");
        L($"| Rows / samples | {s.Rows} / {s.Samples} |");
        L($"| Subjects · visits · tests | {s.Subjects} · {s.Visits} · {s.Tests} |");
        L($"| Values (sample × test) | {s.Cells} |");
        L($"| Missing | {s.Missing} |");
        L($"| Changed by cleaning | {s.Changed} |");
        L($"| Implausible · outliers · suspected artifacts | {s.Implausible} · {s.Outliers} · {s.Artifacts} |");
        L($"| **Clean values (no flags)** | **{F(s.CleanCellsPercent)}%** |");
        L($"| Issues | {Icon["error"]} {s.Issues.Error} errors · {Icon["warning"]} {s.Issues.Warning} warnings · {Icon["info"]} {s.Issues.Info} info |");
        L();
        L("## Issues");
        L();
        if (r.Issues.Count == 0) L("None found.");
        foreach (var i in r.Issues)
        {
            L($"- {Icon[i.Severity]} **{i.Code}**: {i.Message}");
            if (i.Examples.Count > 0)
                L($"  - {(i.Count > i.Examples.Count ? $"{i.Count} affected, e.g. " : "")}{string.Join(", ", i.Examples.Select(e => $"`{e}`"))}");
        }
        L();
        L("## Changes made");
        L();
        if (r.Changes.Count == 0) L("No values were changed.");
        else
        {
            L("| Sample | Test | From | To | Why |");
            L("|---|---|---|---|---|");
            foreach (var c in r.Changes) L($"| {c.Sample} | {c.Test} | {F(c.From)} | {F(c.To)} | {c.Reason.Replace("|", "\\|")} |");
        }
        L();
        L("## Columns");
        L();
        L("| Test | Unit | Unit as written | Value column | Range columns |");
        L("|---|---|---|---|---|");
        foreach (var (t, sc) in r.Schema)
        {
            var ranges = new[] { "min", "max" }.Where(sc.Columns.ContainsKey).Select(k => $"`{sc.Columns[k]}`").ToList();
            L($"| {t}{(sc.Known ? "" : " (unknown)")} | {(sc.Unit == "" ? "—" : sc.Unit)} | {(sc.UnitAsWritten == "" ? "—" : sc.UnitAsWritten)} | `{sc.Columns["value"]}` | {(ranges.Count > 0 ? string.Join(", ", ranges) : "—")} |");
        }
        L();
        L("## Flags used in records.json");
        L();
        L("| Flag | Meaning |");
        L("|---|---|");
        L("| `missing` | No value |");
        L("| `filled_from_identity` | Was blank; computed from related tests |");
        L("| `recomputed_from_identity` | Contradicted a standard formula; recomputed (originalValue kept) |");
        L("| `reassigned` | Value was in the wrong column; moved back (originalValue kept) |");
        L("| `implausible` | Physiologically impossible |");
        L("| `outlier` | Unusual vs population and own history |");
        L("| `corroborated` | Consistent with related tests, so probably real |");
        L("| `possible_sample_artifact` | Likely sample handling; do not alert on it |");
        L("| `visit_cluster` | Many subjects abnormal at this visit; review |");
        L("| `reference_range_changed` | Lab range differs from this subject's usual range |");
        L("| `identity_mismatch` / `suspected_misalignment` | Needs a human check |");
        L("| `censored_below` / `censored_above` | Reported as \"<x\" / \">x\" |");
        L("| `range_missing` | No reference range for this value |");
        L();
        return sb.ToString();
    }
}
